NUM = r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?"


def num(a, k, d="0"):
    return float(a.get(k, d))


def fmt(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def points(s):
    v = [float(t) for t in s.replace(",", " ").split()]
    return list(zip(v[0::2], v[1::2]))


def to_path(tag, a):
    if tag == "path":
        # a leading "m" is absolute in its own <path>, but would become
        # relative to the previous shape once the paths are joined
        # (and the pairs after an "m" are relative lines: "m x y …" = "M x y l …")
        d = a["d"].strip()
        m = re.match(rf"m\s*({NUM})[\s,]*({NUM})(.*)$", d, re.S)
        if not m:
            return d
        rest = m.group(3).lstrip(" ,")
        if rest and not rest[0].isalpha():
            rest = "l" + rest
        return f"M{m.group(1)} {m.group(2)}{rest}"
    if tag == "line":
        return f"M{fmt(num(a,'x1'))} {fmt(num(a,'y1'))}L{fmt(num(a,'x2'))} {fmt(num(a,'y2'))}"
    if tag in ("polyline", "polygon"):
        p = points(a["points"])
        d = "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in p)
        return d + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        cx, cy = num(a, "cx"), num(a, "cy")
        rx = num(a, "r") if tag == "circle" else num(a, "rx")
        ry = num(a, "r") if tag == "circle" else num(a, "ry")
        # two half arcs
        return (f"M{fmt(cx - rx)} {fmt(cy)}"
                f"A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx + rx)} {fmt(cy)}"
                f"A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx - rx)} {fmt(cy)}Z")
    if tag == "rect":
        x, y, w, h = num(a, "x"), num(a, "y"), num(a, "width"), num(a, "height")
        rx = num(a, "rx", a.get("ry", "0"))
        ry = num(a, "ry", a.get("rx", "0"))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0 and ry == 0:
            return f"M{fmt(x)} {fmt(y)}H{fmt(x + w)}V{fmt(y + h)}H{fmt(x)}Z"
        return (f"M{fmt(x + rx)} {fmt(y)}H{fmt(x + w - rx)}"
                f"A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + w)} {fmt(y + ry)}V{fmt(y + h - ry)}"
                f"A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + w - rx)} {fmt(y + h)}H{fmt(x + rx)}"
                f"A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x)} {fmt(y + h - ry)}V{fmt(y + ry)}"
                f"A{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(x + rx)} {fmt(y)}Z")
    raise ValueError(f"unknown shape {tag}")


def main():
    pkg = pathlib.Path(sys.argv[1])
    nodes = json.loads((pkg / "icon-nodes.json").read_text())
    version = json.loads((pkg / "package.json").read_text())["version"]
    out = [
        "// GENERATED by scripts/make-ui-icons.py – do not edit by hand.",
        f"// Icons: Lucide {version} (ISC license, see THIRD-PARTY.md), as SVG path data",
        "// for Slint's Path (view box 24×24, drawn as 1.5 px strokes by `Icon`).",
        "",
        "export global IconData {",
    ]
    for ours, theirs in ICONS.items():
        if theirs not in nodes:
            sys.exit(f"Lucide has no icon '{theirs}' (for '{ours}')")
        d = " ".join(to_path(t, a) for t, a in nodes[theirs])
        out.append(f'    out property <string> {ours}: "{d}";')
    out.append("}")
    out.append("")
    out.append("// every icon with its name (UI kit)")
    out.append("export struct NamedIcon { name: string, d: string }")
    out.append("export global IconList {")
    out.append("    out property <[NamedIcon]> all: [")
    for ours in ICONS:
        prop = ours
        out.append(f'        {{ name: "{ours}", d: IconData.{prop} }},')
    out.append("    ];")
    out.append("}")
    out.append("")
    path = pathlib.Path(__file__).resolve().parent.parent / "crates/app/ui/icons.slint"
    path.write_text("\n".join(out))
    print(f"{len(ICONS)} icons -> {path}")


if __name__ == "__main__":
    main()
