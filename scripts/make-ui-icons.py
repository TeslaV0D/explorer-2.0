#!/usr/bin/env python3
"""Generates crates/app/ui/icons.slint from Lucide (ISC, see THIRD-PARTY.md).

Usage: python3 -I scripts/make-ui-icons.py <lucide-static package dir>
  (npm: lucide-static, the folder with icon-nodes.json)

Only the icons listed in ICONS are taken; every shape (circle, rect, line,
polyline, polygon, ellipse) becomes plain SVG path data, because Slint's
`Path` draws path commands. 24×24 view box, drawn as strokes.
"""
